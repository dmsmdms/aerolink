#!/usr/bin/python3
"""Reference encoder for the AeroLink USB protocol (docs/03-usb-link.md).

Writes protocol/vectors.txt, which the firmware (C) and Android (Kotlin) codec tests consume.
Line format (whitespace separated, '#' starts a comment):

    ok   <name> <type> <seq> <payload_hex|-> <wire_hex>
    bad  <name> <wire_hex>

`wire_hex` is the COBS-encoded frame including the trailing 0x00 delimiter. `bad` frames must be
rejected by the decoder (and counted as rx errors).
"""

import os
import struct

TOOLS_DIR = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(TOOLS_DIR), "protocol", "vectors.txt")

MAX_FRAME = 64


def crc16_ccitt_false(data: bytes) -> int:
    crc = 0xFFFF
    for b in data:
        crc ^= b << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) if crc & 0x8000 else (crc << 1)
            crc &= 0xFFFF
    return crc


def cobs_encode(data: bytes) -> bytes:
    out = bytearray([0])
    code_idx, code = 0, 1
    for b in data:
        if b == 0:
            out[code_idx] = code
            code_idx, code = len(out), 1
            out.append(0)
        else:
            out.append(b)
            code += 1
            if code == 0xFF:
                out[code_idx] = code
                code_idx, code = len(out), 1
                out.append(0)
    out[code_idx] = code
    return bytes(out)


def frame(msg_type: int, seq: int, payload: bytes) -> bytes:
    body = bytes([msg_type, seq]) + payload
    raw = body + struct.pack("<H", crc16_ccitt_false(body))
    assert len(raw) <= MAX_FRAME
    return cobs_encode(raw) + b"\x00"


OK = [
    ("hello", 0x01, 0, struct.pack("<B", 2)),
    ("arm", 0x02, 1, b""),
    ("disarm", 0x03, 2, b""),
    ("drive_forward", 0x04, 3, struct.pack("<hhBH", 500, 0, 1, 250)),
    ("drive_reverse_left", 0x04, 4, struct.pack("<hhBH", -1000, -250, 0, 100)),
    ("drive_zero", 0x04, 255, struct.pack("<hhBH", 0, 0, 2, 0)),
    ("ping", 0x05, 0, b""),
    ("config", 0x06, 7, struct.pack("<HHHH", 600, 1500, 200, 250)),
    ("reboot", 0x07, 8, struct.pack("<IB", 0x544F4F42, 0)),
    ("reboot_bootsel", 0x07, 9, struct.pack("<IB", 0x544F4F42, 1)),
    ("fw_begin", 0x08, 20, struct.pack("<II", 39936, 0x1C291CA3)),
    ("fw_data", 0x09, 21, struct.pack("<I", 4096) + bytes(range(1, 57))),
    ("fw_data_last", 0x09, 22, struct.pack("<I", 39928) + bytes(8)),
    ("fw_end", 0x0A, 23, b""),
    ("fw_confirm", 0x0B, 24, b""),
    ("hello_ack", 0x81, 0, struct.pack("<BBBBI8sIB", 2, 0, 1, 0, 0b100, bytes.fromhex("e66038b3cb3d2a2f"), 0x1C291CA3, 1)),
    ("telemetry", 0x82, 10, struct.pack("<BHHhhhH", 1, 0, 38400, 480, 520, -32768, 3)),
    ("telemetry_fault", 0x82, 11, struct.pack("<BHHhhhH", 3, 0b11, 0, 0, 0, 412, 0)),
    ("event_state", 0x83, 12, struct.pack("<BH", 2, 1)),
    ("nack", 0x84, 1, struct.pack("<BB", 0x02, 3)),
    ("pong", 0x85, 0, b""),
    ("fw_ack", 0x86, 21, struct.pack("<IB", 4096, 0)),
    ("fw_ack_bad_offset", 0x86, 22, struct.pack("<IB", 36864, 2)),
]


def bad_vectors():
    raw = bytes([0x02, 1]) + struct.pack("<H", crc16_ccitt_false(bytes([0x02, 1])))
    yield "bad_crc", cobs_encode(raw[:-1] + bytes([raw[-1] ^ 0xFF])) + b"\x00"
    yield "too_short", cobs_encode(bytes([0x02, 1])) + b"\x00"
    yield "empty", b"\x00"
    yield "bad_cobs", bytes([0x05, 0x02, 0x01]) + b"\x00"  # code byte points past the end
    body = bytes([0x05, 0]) + bytes(range(1, MAX_FRAME - 1))  # decoded length MAX_FRAME + 2
    yield "too_long", cobs_encode(body + struct.pack("<H", crc16_ccitt_false(body))) + b"\x00"


def main():
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    lines = [
        "# AeroLink USB protocol v2 reference frames. Generated by tools/gen_vectors.py, do not edit.",
        "# ok  <name> <type> <seq> <payload_hex|-> <wire_hex>",
        "# bad <name> <wire_hex>",
    ]
    for name, t, seq, payload in OK:
        lines.append(f"ok {name} {t:02x} {seq} {payload.hex() or '-'} {frame(t, seq, payload).hex()}")
    for name, wire in bad_vectors():
        lines.append(f"bad {name} {wire.hex()}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"✅ Wrote {len(OK)} ok + bad vectors to {os.path.relpath(OUT)}")


if __name__ == "__main__":
    main()
